"""Write a table fragment, measure it against the page, and format its cells."""

from __future__ import annotations

import math
import os
import shutil
import subprocess
import tempfile
from collections.abc import Iterable
from pathlib import Path

from . import config as config_module
from . import fit, regen

MISSING_CELL = "--"  # an empty cell reads as an oversight
PNG_DPI = 300

_LATEX_ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def latex_escape(value: object) -> str:
    return "".join(_LATEX_ESCAPES.get(char, char) for char in ("" if value is None else str(value)))


def tex_wrap(value: object) -> str:
    """Escape a long identifier and let it break after each underscore."""
    return latex_escape(value).replace(r"\_", r"\_\allowbreak{}")


def _parse(value: object) -> tuple[float | None, str | None]:
    """A finite number, or the finished cell for anything else."""
    if value is None or (isinstance(value, str) and not value.strip()):
        return None, MISSING_CELL
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None, latex_escape(value)
    if math.isnan(number):
        return None, MISSING_CELL
    if math.isinf(number):
        return None, r"$\infty$" if number > 0 else r"$-\infty$"
    return number, None


def num(value: object, digits: int = 3) -> str:
    """Fixed point."""
    number, cell = _parse(value)
    return f"{number:.{digits}f}" if cell is None else cell


def sci_math(value: object, digits: int = 2) -> str:
    """Scientific notation in math mode."""
    number, cell = _parse(value)
    if cell is not None:
        return cell
    if number == 0:
        return "$0$"
    mantissa, exponent = f"{number:.{digits}e}".split("e")
    return rf"${mantissa}\times 10^{{{int(exponent)}}}$"


def num_or_sci(value: object, digits: int = 4, sci_digits: int = 2, upper: float = 1e4) -> str:
    """Fixed point for ordinary values, scientific notation only for outliers."""
    number, cell = _parse(value)
    if cell is not None:
        return cell
    if number != 0 and not 10**-digits <= abs(number) < upper:
        return sci_math(number, sci_digits)
    return f"{number:.{digits}f}"


def row_line(cells: Iterable[str]) -> str:
    return " & ".join(cells) + r" \\"


def require_columns(row: dict, columns: Iterable[str]) -> None:
    """Raise when the source no longer has a column the table prints."""
    missing = [column for column in columns if column not in row]
    if missing:
        raise KeyError(f"missing columns {missing}; the source has {sorted(row)}")


def provenance(generator: str | Path, source: str) -> str:
    """First line of every generated fragment."""
    root = config_module.load().root
    path = Path(generator).resolve()
    name = path.relative_to(root).as_posix() if path.is_relative_to(root) else path.name
    return f"% Generated by {name} from {source} -- do not edit by hand."


_RENDERERS = {  # command line that writes page 1 of a PDF as a PNG
    "pdftoppm": lambda pdf, png, dpi: ["pdftoppm", "-png", "-r", str(dpi), "-f", "1", "-l", "1", "-singlefile", pdf, png.with_suffix("")],
    "mutool": lambda pdf, png, dpi: ["mutool", "draw", "-q", "-r", str(dpi), "-o", png, pdf, "1"],
    "gs": lambda pdf, png, dpi: ["gs", "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE", "-sDEVICE=png16m", f"-r{dpi}",
                                 "-dFirstPage=1", "-dLastPage=1", f"-sOutputFile={png}", pdf],
}


def _render_png(pdf: Path, png: Path) -> bool | None:
    """Write the table, cropped from page 1 of ``pdf``, as ``png``. Returns whether it changed, None on failure."""
    from PIL import Image, ImageChops

    tool = next((name for name in _RENDERERS if shutil.which(name)), None)
    if tool is None:
        print("  no PNG: install pdftoppm (Poppler), mutool (MuPDF) or gs (Ghostscript) to see the table")
        return None
    with tempfile.TemporaryDirectory(prefix="paper-kit-") as tmp:
        page_png = Path(tmp) / "page.png"
        subprocess.run([str(arg) for arg in _RENDERERS[tool](pdf, page_png, PNG_DPI)], check=True, capture_output=True)
        with Image.open(page_png) as page:
            page = page.convert("RGB")
            box = ImageChops.difference(page, Image.new("RGB", page.size, "white")).getbbox()
            if box is None:
                print("  no PNG: the rendered page is empty")
                return None
            margin = PNG_DPI // 10
            box = (max(box[0] - margin, 0), max(box[1] - margin, 0),
                   min(box[2] + margin, page.width), min(box[3] + margin, page.height))
            page.crop(box).save(page_png.with_name("table.png"), optimize=True)
        new = page_png.with_name("table.png").read_bytes()
    if png.exists() and png.read_bytes() == new:
        return False
    png.write_bytes(new)
    return True


def save(table_tex: str, name: str) -> fit.Fit | None:
    """Write ``<tables_dir>/<name>.tex``, a PNG to look at and the regeneration script, and report the page fit."""
    config = config_module.load()
    target = config.tables_dir / name
    path = target.with_name(f"{name}.tex")
    png = target.with_name(f"{name}.png")
    path.parent.mkdir(parents=True, exist_ok=True)
    changed = not path.exists() or path.read_text(encoding="utf-8") != table_tex
    path.write_text(table_tex, encoding="utf-8")
    written = [path]
    rendered = None
    with tempfile.TemporaryDirectory(prefix="paper-kit-") as tmp:
        pdf = Path(tmp) / "table.pdf"
        result = fit.measure(config, name, table_tex, pdf_out=pdf)
        if pdf.exists():
            rendered = _render_png(pdf, png)
    if rendered is not None:
        written.append(png)
        changed = changed or rendered
    elif png.exists():
        print(f"  {os.path.relpath(png, config.root)} is from an earlier run and may not match the table")
    script = regen.write_script(target, config.root, written, changed)
    if script is not None:
        written.append(script)
    for item in written:
        print(f"wrote {os.path.relpath(item, config.root)}")
    if result is not None:
        result.report()
    return result
